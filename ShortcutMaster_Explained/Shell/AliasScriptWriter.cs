// =====================================================================
// Shell/AliasScriptWriter.cs — עותק עם הסברים
// תפקיד הקובץ: ליצור את קבצי הכינויים — קובץ אחד לכל סוג טרמינל.
// הרעיון (שלב 3): כל קיצור הופך ל"פונקציה" קטנה בטרמינל. למשל עבור gs:
//   PowerShell:  function gs { shortcut __run gs @args }
//   Bash/Zsh:    gs() { shortcut __run gs "$@"; }
//   CMD:         gs=shortcut __run gs $*
// כך מקלידים gs, והטרמינל מפעיל את ShortcutMaster מאחורי הקלעים.
// הקבצים נכתבים מחדש אחרי כל add / update / remove.
// סוגריים מסולסלים { } פותחים וסוגרים בלוק, ולא הוסבר עליהם בנפרד.
// =====================================================================

// ספרייה ל־StringBuilder ולקידודי טקסט (UTF8Encoding).
using System.Text;
// מאפשר להשתמש במודלים.
using ShortcutMaster.Models;
// מאפשר להשתמש ב־AppPaths וב־ShortcutService.
using ShortcutMaster.Services;

// הקובץ שייך לשכבת האינטגרציה עם הטרמינלים.
namespace ShortcutMaster.Shell;

/// <summary>
/// Generates the alias files that PowerShell, CMD and Bash/Zsh load, so each shortcut works by its name alone.
/// </summary>
// מחלקה סטטית שיוצרת את קבצי הכינויים.
public static class AliasScriptWriter
{
    // שורת הסבר שנכתבת בראש כל קובץ, כדי שמי שפותח אותו יבין שלא עורכים אותו ידנית.
    private const string Header = "Generated by ShortcutMaster. Do not edit by hand - use 'shortcut add/update/remove'.";

    /// <summary>
    /// Rewrites all three alias files from the current list of shortcuts.
    /// </summary>
    // כותבת מחדש את שלושת הקבצים.
    public static void WriteAll(IEnumerable<Shortcut> shortcuts)
    {
        // אבטחה: מסננים קיצורים עם שם לא תקין (למשל שנכתב ידנית ל־JSON), כדי שלא ייכנס קוד זדוני לסקריפט.
        List<Shortcut> safeShortcuts = shortcuts.Where(s => ShortcutService.IsValidName(s.Name)).ToList();

        // מוודאים שתיקיית הנתונים קיימת.
        Directory.CreateDirectory(AppPaths.DataFolder);
        // קובץ PowerShell — UTF-8 עם BOM (true), כי Windows PowerShell 5.1 צריך את זה כדי לקרוא נכון עברית.
        File.WriteAllText(AppPaths.PowerShellScript, BuildPowerShell(safeShortcuts), new UTF8Encoding(true));
        // קובץ Bash — UTF-8 בלי BOM (false), כי Bash לא מבין BOM.
        File.WriteAllText(AppPaths.BashScript, BuildBash(safeShortcuts), new UTF8Encoding(false));
        // קובץ CMD — UTF-8 בלי BOM.
        File.WriteAllText(AppPaths.CmdMacroFile, BuildCmd(safeShortcuts), new UTF8Encoding(false));
    }

    /// <summary>
    /// Builds aliases.ps1: one PowerShell function per shortcut.
    /// </summary>
    // בונה את תוכן הקובץ ל־PowerShell.
    private static string BuildPowerShell(IEnumerable<Shortcut> shortcuts)
    {
        // כאן נבנה הטקסט.
        var script = new StringBuilder();
        // שורת הסבר. # = הערה ב־PowerShell.
        script.AppendLine("# " + Header);

        // לכל קיצור...
        foreach (Shortcut shortcut in shortcuts)
        {
            // ...רשימת הצעדים של הפונקציה.
            var steps = new List<string>();
            // אם הקיצור מתחיל ב־cd — זו התיקייה; אחרת null.
            string? folder = GetStartFolder(shortcut);

            // אם יש cd...
            if (folder != null)
                // ...הטרמינל עצמו עובר תיקייה. זה הפתרון לבעיית ה־cd: הפקודה רצה בתוך הטרמינל ולא בתוכנית חיצונית.
                steps.Add($"Set-Location -LiteralPath {QuoteForPowerShell(folder)}");

            // אם יש פעולות שאינן cd...
            if (HasProgramActions(shortcut))
                // ...קוראים ל־ShortcutMaster. @args = מעביר הלאה את כל מה שהמשתמש כתב אחרי הכינוי.
                steps.Add($"shortcut __run {shortcut.Name} @args");

            // ל־PowerShell יש כינויים מובנים, והם גוברים על פונקציות. מוחקים כינוי באותו שם, אם יש.
            script.AppendLine($"Remove-Item -Path Alias:{shortcut.Name} -Force -ErrorAction SilentlyContinue");
            // מגדירים את הפונקציה. global: = זמינה בכל הטרמינל. {{ }} בתוך $"..." = סוגריים מסולסלים רגילים.
            script.AppendLine($"function global:{shortcut.Name} {{ {string.Join("; ", steps)} }}");
        }

        // מחזירים את הטקסט.
        return script.ToString();
    }

    /// <summary>
    /// Builds aliases.sh: one shell function per shortcut, shared by Bash, Zsh and Git Bash.
    /// </summary>
    // בונה את תוכן הקובץ ל־Bash / Zsh / Git Bash.
    private static string BuildBash(IEnumerable<Shortcut> shortcuts)
    {
        // כאן נבנה הטקסט.
        var script = new StringBuilder();
        // שורת הסבר. משתמשים ב־"\n" ולא ב־AppendLine, כי ב־Windows AppendLine מוסיף \r\n — ו־Bash נכשל על \r.
        script.Append("# " + Header + "\n");

        // לכל קיצור...
        foreach (Shortcut shortcut in shortcuts)
        {
            // ...רשימת הצעדים.
            var steps = new List<string>();
            // תיקיית cd, אם יש.
            string? folder = GetStartFolder(shortcut);

            // אם יש cd...
            if (folder != null)
                // ...עוברים תיקייה. || return = אם המעבר נכשל, עוצרים ולא ממשיכים.
                steps.Add($"cd {QuoteForBash(ToBashPath(folder))} || return");

            // אם יש פעולות שאינן cd...
            if (HasProgramActions(shortcut))
                // ...קוראים ל־ShortcutMaster. "$@" = כל הארגומנטים, כל אחד שלם (גם עם רווחים).
                steps.Add($"shortcut __run {shortcut.Name} \"$@\"");

            // פונקציה ב־Bash לא יכולה להיות ריקה...
            if (steps.Count == 0)
                // ...לכן מוסיפים ":" — פקודה שלא עושה כלום.
                steps.Add(":");

            // מוחקים alias קודם באותו שם, אחרת Bash ירחיב אותו ויתבלבל. 2>/dev/null = בלי הודעת שגיאה אם אין.
            script.Append($"unalias {shortcut.Name} 2>/dev/null\n");
            // מגדירים את הפונקציה: name() { צעד; צעד; }
            script.Append($"{shortcut.Name}() {{ {string.Join("; ", steps)}; }}\n");
        }

        // מחזירים את הטקסט.
        return script.ToString();
    }

    /// <summary>
    /// Builds aliases.doskey: one CMD macro per shortcut ($T separates commands, $* passes the arguments).
    /// </summary>
    // בונה את תוכן הקובץ ל־CMD. ב־CMD אין פונקציות, אז משתמשים ב"מאקרו" של doskey.
    private static string BuildCmd(IEnumerable<Shortcut> shortcuts)
    {
        // כאן נבנה הטקסט (בלי שורת הסבר — לקובץ doskey אין תחביר להערות).
        var script = new StringBuilder();

        // לכל קיצור...
        foreach (Shortcut shortcut in shortcuts)
        {
            // ...רשימת הצעדים.
            var steps = new List<string>();
            // תיקיית cd, אם יש.
            string? folder = GetStartFolder(shortcut);

            // אם יש cd...
            if (folder != null)
                // ...cd /d = מעבר תיקייה גם לכונן אחר (D:). $ הוא תו מיוחד ב־doskey, לכן מכפילים אותו.
                steps.Add($"cd /d \"{folder.Replace("$", "$$")}\"");

            // אם יש פעולות שאינן cd...
            if (HasProgramActions(shortcut))
                // ...קוראים ל־ShortcutMaster. $* = כל מה שהמשתמש כתב אחרי הכינוי.
                steps.Add($"shortcut __run {shortcut.Name} $*");

            // אם אין צעדים...
            if (steps.Count == 0)
                // ...rem = הערה, כלומר "לא לעשות כלום".
                steps.Add("rem");

            // שורת מאקרו: name=צעד $T צעד. $T ב־doskey = מפריד בין פקודות.
            script.AppendLine($"{shortcut.Name}={string.Join(" $T ", steps)}");
        }

        // מחזירים את הטקסט.
        return script.ToString();
    }

    /// <summary>
    /// Returns the folder of a leading cd action, or null if the shortcut does not start with one.
    /// </summary>
    // מחזירה את תיקיית ה־cd אם הקיצור מתחיל בה.
    private static string? GetStartFolder(Shortcut shortcut)
    {
        // הפעולה הראשונה, או null אם אין פעולות בכלל.
        ShortcutAction? first = shortcut.Actions.FirstOrDefault();
        // אם יש פעולה ראשונה והיא cd — מחזירים את התיקייה; אחרת null.
        return first != null && first.Is(ShortcutTypes.Cd) ? first.Target : null;
    }

    /// <summary>
    /// Returns true if the shortcut has any action that must be run by the ShortcutMaster program.
    /// </summary>
    // בודקת אם יש פעולה שאינה cd (ולכן צריך לקרוא לתוכנית).
    private static bool HasProgramActions(Shortcut shortcut)
    {
        // Any = האם קיימת לפחות פעולה אחת שעומדת בתנאי.
        return shortcut.Actions.Any(action => !action.Is(ShortcutTypes.Cd));
    }

    /// <summary>
    /// Wraps text in single quotes for PowerShell, doubling any single quote inside it.
    /// </summary>
    // עוטפת טקסט במרכאות בודדות ל־PowerShell, כך שתווים מיוחדים בנתיב לא ייפרשו כקוד.
    private static string QuoteForPowerShell(string text)
    {
        // ב־PowerShell, ' בתוך '...' כותבים כ־''.
        return "'" + text.Replace("'", "''") + "'";
    }

    /// <summary>
    /// Wraps text in single quotes for Bash, escaping any single quote inside it.
    /// </summary>
    // עוטפת טקסט במרכאות בודדות ל־Bash.
    private static string QuoteForBash(string text)
    {
        // ב־Bash, ' בתוך '...' כותבים כ־'\'' (סוגרים, ' מוגן, ופותחים מחדש).
        return "'" + text.Replace("'", "'\\''") + "'";
    }

    /// <summary>
    /// Converts a Windows path like C:\Projects to the Git Bash form /c/Projects. Other paths are unchanged.
    /// </summary>
    // ממירה נתיב Windows לצורה ש־Git Bash מבין. ציבורית, כי גם ShellInstaller משתמש בה.
    public static string ToBashPath(string path)
    {
        // ב־Linux/macOS הנתיבים כבר בצורה הנכונה...
        if (!OperatingSystem.IsWindows())
            // ...מחזירים כמו שהוא.
            return path;

        // מחליפים \ ב־/.
        string forward = path.Replace('\\', '/');

        // אם הנתיב מתחיל באות כונן ונקודתיים (C:)...
        if (forward.Length >= 2 && forward[1] == ':')
            // ...הופכים "C:/Projects" ל־"/c/Projects".
            return "/" + char.ToLowerInvariant(forward[0]) + forward.Substring(2);

        // אחרת — רק עם הלוכסנים המוחלפים.
        return forward;
    }
}
