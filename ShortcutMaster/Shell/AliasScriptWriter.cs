using System.Text;
using ShortcutMaster.Models;
using ShortcutMaster.Services;

namespace ShortcutMaster.Shell;

/// <summary>
/// Generates the alias files that PowerShell, CMD and Bash/Zsh load, so each shortcut works by its name alone.
/// </summary>
public static class AliasScriptWriter
{
    private const string Header = "Generated by ShortcutMaster. Do not edit by hand - use 'shortcut add/update/remove'.";

    /// <summary>
    /// Rewrites all three alias files from the current list of shortcuts.
    /// </summary>
    public static void WriteAll(IEnumerable<Shortcut> shortcuts)
    {
        List<Shortcut> safeShortcuts = shortcuts.Where(s => ShortcutService.IsValidName(s.Name)).ToList();

        Directory.CreateDirectory(AppPaths.DataFolder);
        File.WriteAllText(AppPaths.PowerShellScript, BuildPowerShell(safeShortcuts), new UTF8Encoding(true));
        File.WriteAllText(AppPaths.BashScript, BuildBash(safeShortcuts), new UTF8Encoding(false));
        File.WriteAllText(AppPaths.CmdMacroFile, BuildCmd(safeShortcuts), new UTF8Encoding(false));
    }

    /// <summary>
    /// Builds aliases.ps1: one PowerShell function per shortcut.
    /// </summary>
    private static string BuildPowerShell(IEnumerable<Shortcut> shortcuts)
    {
        var script = new StringBuilder();
        script.AppendLine("# " + Header);

        foreach (Shortcut shortcut in shortcuts)
        {
            var steps = new List<string>();
            string? folder = GetStartFolder(shortcut);

            if (folder != null)
                steps.Add($"Set-Location -LiteralPath {QuoteForPowerShell(folder)}");

            if (HasProgramActions(shortcut))
                steps.Add($"shortcut __run {shortcut.Name} @args");

            script.AppendLine($"Remove-Item -Path Alias:{shortcut.Name} -Force -ErrorAction SilentlyContinue");
            script.AppendLine($"function global:{shortcut.Name} {{ {string.Join("; ", steps)} }}");
        }

        return script.ToString();
    }

    /// <summary>
    /// Builds aliases.sh: one shell function per shortcut, shared by Bash, Zsh and Git Bash.
    /// </summary>
    private static string BuildBash(IEnumerable<Shortcut> shortcuts)
    {
        var script = new StringBuilder();
        script.Append("# " + Header + "\n");

        foreach (Shortcut shortcut in shortcuts)
        {
            var steps = new List<string>();
            string? folder = GetStartFolder(shortcut);

            if (folder != null)
                steps.Add($"cd {QuoteForBash(ToBashPath(folder))} || return");

            if (HasProgramActions(shortcut))
                steps.Add($"shortcut __run {shortcut.Name} \"$@\"");

            if (steps.Count == 0)
                steps.Add(":");

            script.Append($"unalias {shortcut.Name} 2>/dev/null\n");
            script.Append($"{shortcut.Name}() {{ {string.Join("; ", steps)}; }}\n");
        }

        return script.ToString();
    }

    /// <summary>
    /// Builds aliases.doskey: one CMD macro per shortcut ($T separates commands, $* passes the arguments).
    /// </summary>
    private static string BuildCmd(IEnumerable<Shortcut> shortcuts)
    {
        var script = new StringBuilder();

        foreach (Shortcut shortcut in shortcuts)
        {
            var steps = new List<string>();
            string? folder = GetStartFolder(shortcut);

            if (folder != null)
                steps.Add($"cd /d \"{folder.Replace("$", "$$")}\"");

            if (HasProgramActions(shortcut))
                steps.Add($"shortcut __run {shortcut.Name} $*");

            if (steps.Count == 0)
                steps.Add("rem");

            script.AppendLine($"{shortcut.Name}={string.Join(" $T ", steps)}");
        }

        return script.ToString();
    }

    /// <summary>
    /// Returns the folder of a leading cd action, or null if the shortcut does not start with one.
    /// </summary>
    private static string? GetStartFolder(Shortcut shortcut)
    {
        ShortcutAction? first = shortcut.Actions.FirstOrDefault();
        return first != null && first.Is(ShortcutTypes.Cd) ? first.Target : null;
    }

    /// <summary>
    /// Returns true if the shortcut has any action that must be run by the ShortcutMaster program.
    /// </summary>
    private static bool HasProgramActions(Shortcut shortcut)
    {
        return shortcut.Actions.Any(action => !action.Is(ShortcutTypes.Cd));
    }

    /// <summary>
    /// Wraps text in single quotes for PowerShell, doubling any single quote inside it.
    /// </summary>
    private static string QuoteForPowerShell(string text)
    {
        return "'" + text.Replace("'", "''") + "'";
    }

    /// <summary>
    /// Wraps text in single quotes for Bash, escaping any single quote inside it.
    /// </summary>
    private static string QuoteForBash(string text)
    {
        return "'" + text.Replace("'", "'\\''") + "'";
    }

    /// <summary>
    /// Converts a Windows path like C:\Projects to the Git Bash form /c/Projects. Other paths are unchanged.
    /// </summary>
    public static string ToBashPath(string path)
    {
        if (!OperatingSystem.IsWindows())
            return path;

        string forward = path.Replace('\\', '/');

        if (forward.Length >= 2 && forward[1] == ':')
            return "/" + char.ToLowerInvariant(forward[0]) + forward.Substring(2);

        return forward;
    }
}
